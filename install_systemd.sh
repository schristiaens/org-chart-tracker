#!/bin/sh
# Install the daily systemd USER timer for org_tracker.py on Linux.
#
# Usage:  sh install_systemd.sh          install / update (daily 09:05)
#         sh install_systemd.sh remove   disable and delete
#         sh install_systemd.sh status   show timer + last run
#
# A user timer (not a system unit) keeps the credential in your own home and
# needs no root. `loginctl enable-linger` is what lets it run while you are
# logged out -- without it the timer only fires during an active session,
# which is the single most common way a setup like this silently never runs.
set -e

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
BASE="${BHR_ORG_TRACKER_HOME:-$SCRIPT_DIR}"
LOG="$BASE/tracker.log"
RUNNER="$SCRIPT_DIR/run_daily.sh"
SECRETS="${BHR_SECRETS_FILE:-$HOME/.secrets.env}"
SUBDOMAIN="${BHR_SUBDOMAIN:-}"
UNIT_DIR="$HOME/.config/systemd/user"
NAME="bhr-org-tracker"
ONCAL="${BHR_TRACKER_ONCALENDAR:-*-*-* 09:05:00}"

# single-quote a value for the shell
sq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }

case "$1" in
remove)
    systemctl --user disable --now "$NAME.timer" 2>/dev/null || true
    rm -f "$UNIT_DIR/$NAME.timer" "$UNIT_DIR/$NAME.service"
    systemctl --user daemon-reload 2>/dev/null || true
    echo "timer removed (runner and secrets left in place)"
    exit 0
    ;;
status)
    systemctl --user list-timers "$NAME.timer" --all || true
    echo
    systemctl --user status "$NAME.service" --no-pager -n 20 2>/dev/null || true
    exit 0
    ;;
esac

[ -n "$SUBDOMAIN" ] || {
    echo "refusing to install: set BHR_SUBDOMAIN (your <name>.bamboohr.com)." >&2
    exit 1
}
[ -f "$SECRETS" ] || {
    echo "refusing to install: secrets file not found at $SECRETS" >&2
    echo "see .env.example for the variables it must export." >&2
    exit 1
}
command -v python3 >/dev/null 2>&1 || { echo "python3 not found" >&2; exit 1; }

PYVER=$(python3 -c 'import sys;print("%d.%d"%sys.version_info[:2])')
echo "python3 $PYVER at $(command -v python3)"

# --- runner: sources secrets, then runs the tracker ----------------------
umask 077
cat > "$RUNNER" <<RUNNEREOF
#!/bin/sh
# Generated by the installer -- edit the installer, not this file.
set -u
[ -f "$SECRETS" ] || { echo "secrets file missing: $SECRETS" >&2; exit 1; }
. "$SECRETS"
export BHR_SUBDOMAIN="\${BHR_SUBDOMAIN:-$SUBDOMAIN}"
export BHR_ORG_TRACKER_HOME="$BASE"
# Daily pull first, then any weekly/monthly roll-up that is due. The roll-up
# step runs even if the pull failed -- a monthly must not be lost to one bad
# morning -- and the exit code is non-zero if either step failed.
rc=0
python3 "$SCRIPT_DIR/org_tracker.py" --run --email || rc=\$?
python3 "$SCRIPT_DIR/org_tracker.py" --rollup auto --email || rc=\$?
exit \$rc
RUNNEREOF
chmod 700 "$RUNNER"

# --- no systemd: the runner is all cron needs -----------------------------
# Hand over a crontab line for the configured time. Only the simple
# '*-*-* HH:MM[:SS]' calendar form maps onto cron; anything else gets 09:05.
if ! command -v systemctl >/dev/null 2>&1; then
    H=9 M=5 NOTE=""
    case "$ONCAL" in
    '*-*-* '[0-9]:[0-5][0-9] | '*-*-* '[0-9]:[0-5][0-9]:[0-5][0-9] | \
    '*-*-* '[0-2][0-9]:[0-5][0-9] | '*-*-* '[0-2][0-9]:[0-5][0-9]:[0-5][0-9])
        T=${ONCAL#'*-*-* '}; H=${T%%:*}; T=${T#*:}; M=${T%%:*}
        H=${H#0}; H=${H:-0}; M=${M#0}; M=${M:-0}
        [ "$H" -le 23 ] || { H=9 M=5 NOTE="bad hour"; } ;;
    *) NOTE="not simple" ;;
    esac
    mkdir -p "$BASE"   # cron's '>>' needs the log's folder to exist
    # single-quote for the shell cron runs; cron itself needs '%' escaped
    q() { sq "$1" | sed 's/%/\\%/g'; }
    echo "systemctl not found, so no timer was installed. The runner is ready;"
    echo "add this line with 'crontab -e' to run it daily at $(printf '%02d:%02d' "$H" "$M"):"
    echo
    printf '%s\n' "    $M $H * * * /bin/sh $(q "$RUNNER") >> $(q "$LOG") 2>&1"
    echo
    if [ -n "$NOTE" ]; then
        printf '%s\n' "note: BHR_TRACKER_ONCALENDAR='$ONCAL' is not the simple '*-*-* HH:MM'"
        echo "      form, so the line above uses 09:05 -- edit its first two fields."
    fi
    exit 0
fi

mkdir -p "$UNIT_DIR"
# systemd splits ExecStart on unquoted spaces (hence the quotes below) and
# expands %-specifiers everywhere, so a literal '%' is written '%%'
sd() { printf '%s' "$1" | sed 's/%/%%/g'; }

cat > "$UNIT_DIR/$NAME.service" <<UNITEOF
[Unit]
Description=BambooHR org-chart snapshot and change report
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/bin/sh "$(sd "$RUNNER")"
StandardOutput=append:$(sd "$LOG")
StandardError=append:$(sd "$LOG")
# the report is small; keep the run from wedging the timer forever
TimeoutStartSec=900
UNITEOF

cat > "$UNIT_DIR/$NAME.timer" <<TIMEREOF
[Unit]
Description=Daily BambooHR org-chart tracker

[Timer]
OnCalendar=$ONCAL
# catch up if the box was asleep or off at the scheduled time
Persistent=true
RandomizedDelaySec=300

[Install]
WantedBy=timers.target
TIMEREOF

systemctl --user daemon-reload
systemctl --user enable --now "$NAME.timer"

# without linger, a user timer does not run while logged out
if command -v loginctl >/dev/null 2>&1; then
    if [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" != "yes" ]; then
        echo
        echo "IMPORTANT: linger is off, so this timer will NOT run while you are"
        echo "logged out. Enable it once (needs sudo):"
        echo "    sudo loginctl enable-linger $USER"
    fi
fi

echo
echo "installed: $NAME.timer ($ONCAL)"
echo "  runner:  $RUNNER (0700, sources $SECRETS)"
echo "  log:     $LOG"
echo
echo "verify:      sh install_systemd.sh status"
echo "run now:     systemctl --user start $NAME.service"
echo "test email:  ( . $(sq "$SECRETS") && python3 $(sq "$SCRIPT_DIR/org_tracker.py") --test-email )"
