#!/bin/sh
# Install the daily launchd job for org_tracker.py.
#
# Usage:  sh install_cron.sh          install / update (daily 09:05)
#         sh install_cron.sh remove   unload and delete
#
# The job sources a secrets file at run time rather than baking credentials
# into the plist, so the key lives in exactly one place and rotating it needs
# no reinstall. Override the file with BHR_SECRETS_FILE.
set -e

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
BASE="${BHR_ORG_TRACKER_HOME:-$SCRIPT_DIR}"
LOG="$BASE/tracker.log"
LABEL="com.bhr-org-tracker"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
RUNNER="$SCRIPT_DIR/run_daily.sh"
SECRETS="${BHR_SECRETS_FILE:-$HOME/.secrets.env}"
SUBDOMAIN="${BHR_SUBDOMAIN:-}"
HOUR="${BHR_TRACKER_HOUR:-9}"
MINUTE="${BHR_TRACKER_MINUTE:-5}"

if [ "$1" = "remove" ]; then
    launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
    rm -f "$PLIST"
    echo "tracker job removed (runner and secrets left in place)"
    exit 0
fi

[ -n "$SUBDOMAIN" ] || {
    echo "refusing to install: set BHR_SUBDOMAIN (your <name>.bamboohr.com)." >&2
    exit 1
}
if [ ! -f "$SECRETS" ]; then
    echo "refusing to install: secrets file not found at $SECRETS" >&2
    echo "it must export BHR_PERSONAL_API_KEY (or BHR_SESSION_COOKIE)." >&2
    exit 1
fi

# --- the runner: sources secrets, then runs the tracker -------------------
umask 077
cat > "$RUNNER" <<RUNNEREOF
#!/bin/sh
# Generated by install_cron.sh -- edit the installer, not this file.
set -u
[ -f "$SECRETS" ] || { echo "secrets file missing: $SECRETS" >&2; exit 1; }
. "$SECRETS"
export BHR_SUBDOMAIN="\${BHR_SUBDOMAIN:-$SUBDOMAIN}"
export BHR_ORG_TRACKER_HOME="$BASE"
# Daily pull first, then any weekly/monthly roll-up that is due. The roll-up
# step runs even if the pull failed -- a monthly must not be lost to one bad
# morning -- and the exit code is non-zero if either step failed.
rc=0
"$SCRIPT_DIR/org_tracker.py" --run --email --notify || rc=\$?
"$SCRIPT_DIR/org_tracker.py" --rollup auto --email --notify || rc=\$?
exit \$rc
RUNNEREOF
chmod 700 "$RUNNER"

# --- the launchd job ------------------------------------------------------
mkdir -p "$HOME/Library/LaunchAgents"
cat > "$PLIST" <<PLISTEOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>/bin/sh</string>
        <string>$RUNNER</string>
    </array>
    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin</string>
    </dict>
    <key>StartCalendarInterval</key>
    <dict>
        <key>Hour</key><integer>$HOUR</integer>
        <key>Minute</key><integer>$MINUTE</integer>
    </dict>
    <key>StandardOutPath</key>
    <string>$LOG</string>
    <key>StandardErrorPath</key>
    <string>$LOG</string>
    <key>RunAtLoad</key>
    <false/>
</dict>
</plist>
PLISTEOF
chmod 644 "$PLIST"

# Clickable notifications need terminal-notifier, and terminal-notifier needs
# a macOS permission record -- which only exists once its app bundle has been
# launched. Register it now so the scheduled run is not the thing that discovers
# it cannot post. Without it the tracker still notifies, just not clickably.
NOTIFIER_APP=/opt/homebrew/opt/terminal-notifier/terminal-notifier.app
if [ -d "$NOTIFIER_APP" ]; then
    open "$NOTIFIER_APP" 2>/dev/null || true
    echo "registered terminal-notifier for notifications"
else
    echo "note: terminal-notifier not installed -- notifications will post but"
    echo "      will not be clickable. brew install terminal-notifier"
fi

launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
echo "tracker job installed: daily at $(printf '%02d:%02d' "$HOUR" "$MINUTE")"
echo "  runner:  $RUNNER (0700, sources $SECRETS)"
echo "  plist:   $PLIST (carries no secrets)"
echo "  log:     $LOG"
echo "run once now:  launchctl kickstart -p gui/$(id -u)/$LABEL"
